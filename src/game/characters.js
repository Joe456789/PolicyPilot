// 由 AI 產生的自訂角色,經過夾限(clamp)後才會進入遊戲,避免數值失控。
export function sanitizeCustomCharacter(raw) {
  const clamp = (v, a, b, d) => {
    const n = Number(v)
    return Number.isFinite(n) ? Math.min(b, Math.max(a, n)) : d
  }
  const age = Math.round(clamp(raw.age, 22, 58, 30))
  const dependents = Math.round(clamp(raw.dependents, 0, 4, 0))
  const income = Math.round(clamp(raw.income, 360000, 3600000, 900000) / 10000) * 10000
  const expense = Math.round(clamp(raw.expense, 240000, income * 0.95, income * 0.7) / 10000) * 10000
  const soleEarner = !!raw.soleEarner
  const rec = {
    medical: 1,
    critical: income > 1500000 || dependents > 0 ? 2 : 1,
    disability: dependents > 0 || soleEarner ? 2 : 1,
    life: dependents >= 2 ? 3 : dependents === 1 || soleEarner ? 2 : age > 28 && raw.family ? 1 : 0,
    annuity: income > 1200000 ? 1 : 0,
    ltc: age >= 45 ? 1 : 0,
  }
  const avatars = ['short', 'long', 'bun', 'ponytail', 'messy', 'side', 'bob']
  const tops = ['#4f8cff', '#ff7aa2', '#2eb67d', '#9b6bff', '#ff9f43', '#37474f', '#c2185b']
  const k = (age + dependents) % tops.length
  return {
    id: 'custom',
    custom: true,
    name: String(raw.name || '自訂角色').slice(0, 12),
    title: String(raw.title || '自訂角色').slice(0, 14),
    age,
    years: Math.round(clamp(raw.years, 10, 15, 14)),
    tagline: String(raw.tagline || '由 AI 依你的描述量身打造。').slice(0, 60),
    traits: Array.isArray(raw.traits) ? raw.traits.slice(0, 3).map((t) => String(t).slice(0, 8)) : ['自訂'],
    income,
    expense,
    cash: Math.round(clamp(raw.cash, 0, 3000000, 200000) / 10000) * 10000,
    invest: Math.round(clamp(raw.invest, 0, 5000000, 100000) / 10000) * 10000,
    debt: Math.round(clamp(raw.debt, 0, 2000000, 0) / 10000) * 10000,
    mortgage: Math.round(clamp(raw.mortgage, 0, 12000000, 0) / 10000) * 10000,
    dependents,
    volatility: clamp(raw.volatility, 0.01, 0.3, 0.03),
    laborIns: raw.laborIns !== false,
    family: !!raw.family,
    soleEarner,
    avatar: {
      skin: ['#f3c9a5', '#e9b98f', '#f6d2b0', '#eebb94'][k % 4],
      hair: ['#2b2118', '#5a3b2e', '#7a4b2a', '#1f1a17'][(k + 1) % 4],
      style: avatars[k % avatars.length],
      top: tops[k],
      accent: '#ffe3c2',
      extra: 'none',
    },
    rec,
    focus: String(raw.focus || '依你描述的處境,找出最需要補強的風險。').slice(0, 80),
  }
}
